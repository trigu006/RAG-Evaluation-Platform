"""
    Initiate a generator that will receive the input generated by the retriever to answer questions.
"""

from langchain_ollama import ChatOllama

def create_generator(model, temperature: float =0.0, **kwargs):
    """
    Create a generator instance for answering questions based on retrieved information.
    """

    llm = ChatOllama(model=model,
                     temperature=temperature,
                     **kwargs)

    return llm